HEADER = '''package dev.retrobit.agent.ui.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

/**
 * RetroBit pixel icon set.
 *
 * Every glyph is authored on a 12x12 grid and drawn with 2x2 unit blocks in a
 * 24x24 viewport, so strokes stay thick and readable from 14 dp up. Shapes share
 * one optical weight and a consistent silhouette.
 *
 * Regenerate with `python3 tools/pixel_icons.py kotlin`.
 */
object PixelIcons {
    private fun icon(name: String, path: String): ImageVector =
        ImageVector.Builder(
            name = name,
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = 24f,
            viewportHeight = 24f,
        ).addPath(pathData = addPathNodes(path), fill = SolidColor(Color.Black))
            .build()
'''


def emit_kotlin(icons: dict[str, list[str]], path: Path) -> None:
    out = [HEADER]
    for name, art in icons.items():
        out.append(f'    val {name}: ImageVector by lazy {{ icon("{name}", "{path_data(art)}") }}\n')
    out.append("}\n")
    path.write_text("".join(out))
    print(f"wrote {path} ({len(icons)} icons)")


def main() -> None:
    by_name = dict(ICONS)
    for name, art in by_name.items():
        validate(name, art)
    cmd = sys.argv[1] if len(sys.argv) > 1 else "render"
    if cmd == "render":
        contact_sheet(by_name, SHEET)
    elif cmd == "kotlin":
        emit_kotlin(by_name, KOTLIN)
    else:
        raise SystemExit(f"unknown command: {cmd}")


if __name__ == "__main__":
    main()
