"""RetroBit pixel icon generator.

Icons are authored as 12x12 ASCII grids. Every cell becomes a 2x2 unit block in
a 24x24 viewport, so strokes stay crisp and share one optical weight from 14 dp
up. Keeping the artwork in Python makes it cheap to review every glyph on a
contact sheet before it lands in the app.

Usage:
    python3 tools/pixel_icons.py render  # write build/icon-sheet.png
    python3 tools/pixel_icons.py kotlin  # write PixelIcons.kt
"""

